"""`openport capture`: draft a starter eval spec for a repo, so `openport tune` has something to run.

For each LLM call the scanner can drive, capture writes a call-site entry, a grader and a dataset.
Cases come from recorded logs when you have them, or are generated by Super and labelled by Ultra.
The result is a reviewable openport.evals.yaml plus one JSONL per call and a notes file.
"""

import json
import os
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from .. import config, tokenfactory
from ..runtime.openport_llm import UsageMeter
from ..scan import ScanReport
from ..scan.findings import CallSiteFinding
from . import draft as _draft
from .logs import infer_fields, load_log_cases

SPEC_FILE = "openport.evals.yaml"


@dataclass
class DraftedSite:
    finding: CallSiteFinding
    spec: dict
    cases: list[dict]
    source: str  # "logs", "generated" or "none"
    notes: list[str] = field(default_factory=list)


@dataclass
class CaptureResult:
    target: str
    source_root: Path
    sites: list[DraftedSite]
    skipped: list[tuple[str, str]]  # (call-site id, why it was skipped)
    helper_cost_usd: float | None = None


def _notes(finding: CallSiteFinding, spec: dict, source: str) -> list[str]:
    notes: list[str] = []
    if source == "generated":
        notes.append("cases generated by Super/Ultra — review them before trusting the numbers")
    elif source == "none":
        notes.append("no cases yet: add --logs ID=PATH, or re-run with --generate N")
    grader = spec["grader"]
    if grader["type"] == "fields" and not grader["fields"]:
        notes.append("field grader has no fields: add the output keys that must match")
    if finding.output == "json_schema":
        notes.append("structured output: a bespoke grader may judge it better than field equality")
    if finding.output == "tools":
        notes.append("tool call: confirm the grader checks the tool name and its arguments")
    return notes


def _helper_cost(meter: UsageMeter) -> float | None:
    total = 0.0
    for model, usage in meter.by_model.items():
        try:
            info = tokenfactory.model_info(model)
        except Exception:
            return None
        if info is None:
            return None
        total += info.cost(usage.prompt_tokens, usage.completion_tokens)
    return total


def capture_repo(
    root: Path,
    report: ScanReport,
    *,
    logs: dict[str, Path] | None = None,
    generate: int = 0,
    label: str = "ultra",
    include_tests: bool = False,
    on_site=None,
) -> CaptureResult:
    logs = logs or {}
    meter = UsageMeter() if generate else None
    sites: list[DraftedSite] = []
    skipped: list[tuple[str, str]] = []

    for finding in report.portable(include_tests):
        ok, reason = _draft.runnable(finding, root)
        if not ok:
            skipped.append((finding.id, reason))
            continue

        cases: list[dict] = []
        source = "none"
        if finding.id in logs:
            cases = load_log_cases(logs[finding.id], finding.id)
            source = "logs"
        elif generate:
            from .generate import generate_cases, original_labeller

            needs_label = finding.output != "text"
            labeller = None
            if label == "original" and needs_label and finding.language == "python":  # TypeScript is labelled by Ultra
                key_env = "OPENAI_API_KEY" if finding.sdk == "openai" else "ANTHROPIC_API_KEY"
                value = os.getenv(key_env)
                if not value or value == "openport-placeholder":
                    raise config.MissingKeyError(
                        f"--label-with original needs a real {key_env} to run {finding.id} through its original model."
                    )
                labeller = original_labeller(root, finding.module, finding.function)

            file_source = (root / finding.file).read_text(encoding="utf-8", errors="replace")
            cases = generate_cases(
                finding.id,
                _draft.humanize_title(finding),
                finding.function,
                _draft.param_names(root, finding),
                file_source,
                n=generate,
                needs_label=needs_label,
                labeller=labeller,
                meter=meter,
            )
            source = "generated"

        fields = infer_fields(cases) if finding.output != "text" else None
        spec = _draft.draft_site(finding, fields=fields, args=_draft.param_names(root, finding) if finding.language != "python" else None)
        site = DraftedSite(finding, spec, cases, source, _notes(finding, spec, source))
        sites.append(site)
        if on_site is not None:
            on_site(site)

    cost = _helper_cost(meter) if meter is not None else None
    return CaptureResult(Path(report.root).name, Path(report.root), sites, skipped, cost)


def render_notes(result: CaptureResult) -> str:
    lines = [
        f"# Capture notes for {result.target}",
        "",
        "OpenPort drafted this eval spec from a scan. Review it before tuning: grader details and",
        "generated cases in particular need a human eye. Then run `openport tune` against this folder.",
        "",
        "## Call sites",
        "",
    ]
    for site in result.sites:
        lines.append(f"### {site.spec['id']} — {site.spec['title']}")
        lines.append(f"- {len(site.cases)} case(s), from {site.source}")
        lines.append(f"- grader: {site.spec['grader']['type']}")
        for note in site.notes:
            lines.append(f"- [ ] {note}")
        lines.append("")
    if result.skipped:
        lines.append("## Skipped call sites")
        lines.append("")
        for site_id, reason in result.skipped:
            lines.append(f"- {site_id}: {reason}")
        lines.append("")
    return "\n".join(lines)


def write_capture(result: CaptureResult, out_dir: Path) -> dict:
    evals = Path(out_dir) / "evals"
    evals.mkdir(parents=True, exist_ok=True)
    try:
        source_root = os.path.relpath(result.source_root, evals).replace(os.sep, "/")
    except ValueError:  # a different drive on Windows: no relative path exists
        source_root = Path(result.source_root).as_posix()

    spec = {
        "target": result.target,
        "source_root": source_root,
        "call_sites": [site.spec for site in result.sites],
    }
    spec_path = evals / SPEC_FILE
    spec_path.write_text(yaml.safe_dump(spec, sort_keys=False, allow_unicode=True, width=100), encoding="utf-8")

    datasets = []
    for site in result.sites:
        path = evals / site.spec["dataset"]
        path.write_text("".join(json.dumps(case, ensure_ascii=False) + "\n" for case in site.cases), encoding="utf-8")
        datasets.append(path)

    notes_path = evals / "CAPTURE_NOTES.md"
    notes_path.write_text(render_notes(result), encoding="utf-8")
    return {"spec": spec_path, "datasets": datasets, "notes": notes_path}


__all__ = ["CaptureResult", "DraftedSite", "capture_repo", "render_notes", "write_capture"]
